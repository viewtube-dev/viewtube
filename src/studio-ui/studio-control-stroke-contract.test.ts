import { describe, expect, it } from "vitest"
import { STUDIO_CONTROL_SIZE_BASE, STUDIO_DROPDOWN_TOKENS } from "./tokens"
import { readFileSync } from "node:fs"

describe("Studio global stroke-tier contract", () => {
  it("uses the Standard stroke system for Supreme", () => {
    expect(STUDIO_CONTROL_SIZE_BASE.supreme.stroke).toBe(3)
    expect(STUDIO_CONTROL_SIZE_BASE.supreme.textStroke).toBe(1)
    expect(STUDIO_CONTROL_SIZE_BASE.supreme.focusOutlineWidth).toBe(1.95)
    expect(STUDIO_CONTROL_SIZE_BASE.supreme.secondaryFocusOutlineWidth).toBe(1.95)
    expect(STUDIO_CONTROL_SIZE_BASE.supreme.iconStroke).toBe(1.9)
    expect(STUDIO_DROPDOWN_TOKENS.chevronStroke.supreme).toBe(STUDIO_DROPDOWN_TOKENS.chevronStroke.standard)
  })

  it("uses the Mini stroke system for Micro", () => {
    expect(STUDIO_CONTROL_SIZE_BASE.micro.stroke).toBe(1.5)
    expect(STUDIO_CONTROL_SIZE_BASE.micro.textStroke).toBe(0.375)
    expect(STUDIO_CONTROL_SIZE_BASE.micro.focusOutlineWidth).toBe(0.975)
    expect(STUDIO_CONTROL_SIZE_BASE.micro.secondaryFocusOutlineWidth).toBe(0.975)
    expect(STUDIO_CONTROL_SIZE_BASE.micro.iconStroke).toBe(STUDIO_CONTROL_SIZE_BASE.mini.iconStroke)
    expect(STUDIO_DROPDOWN_TOKENS.chevronStroke.micro).toBe(STUDIO_DROPDOWN_TOKENS.chevronStroke.mini)
  })

  it("does not retain the retired Supreme/Micro stroke overrides in shared CSS", () => {
    const css = readFileSync("src/styles/studio-control-system.css", "utf8")
    const fieldsCss = readFileSync("src/styles/studio-control-fields.css", "utf8")
    const textInputCss = readFileSync("src/styles/studio-text-input.css", "utf8")
    const controls = readFileSync("src/studio-ui/primitives/StudioControls.tsx", "utf8")
    const catalog = readFileSync("src/components/studio-hub/StudioHubConfirmedPrimitiveCatalog.tsx", "utf8")
    const generated = readFileSync("src/styles/studio-control-vars.generated.css", "utf8")
    expect(generated).toContain("--vt-studio-supreme-stroke: 3px;")
    expect(generated).toContain("--vt-studio-supreme-text-stroke: 1px;")
    expect(generated).toContain("--vt-studio-supreme-focus-outline-width: 1.95px;")
    expect(generated).toContain("--vt-studio-micro-stroke: 1.5px;")
    expect(generated).toContain("--vt-studio-micro-text-stroke: 0.375px;")
    expect(generated).toContain("--vt-studio-micro-focus-outline-width: 0.975px;")
    expect(generated).toContain("--vt-studio-textarea-supreme-font-size: 25px;")
    expect(generated).toContain("--vt-studio-textarea-supreme-text-stroke: 0.5px;")
    expect(generated).toContain("--vt-studio-dropdown-supreme-chevron-stroke: 2.5;")
    expect(generated).toContain("--vt-studio-dropdown-micro-chevron-stroke: 1.2;")
    expect(css).not.toContain("4.09px")
    expect(css).not.toContain("2.66px")
    expect(css).not.toContain("1.36px")
    expect(css).not.toContain("2.59")
    expect(css).not.toContain("micro-stroke, 1px")
    expect(css).not.toContain("micro-text-stroke, 0.25px")
    expect(fieldsCss).not.toContain("--vt-studio-micro-text-stroke, .25px")
    expect(fieldsCss).not.toContain("--vt-studio-textarea-micro-text-stroke, .25px")
    expect(textInputCss).toContain("--vt-studio-micro-stroke, 1.5px")
    expect(css).toContain('data-size="micro"] { min-height: 12px; font-size: 10px; border-width: 1.5px; border-radius: 2px; }')
    expect(css).toContain("--vt-studio-control-stroke: 1.5px")
    expect(css).not.toContain("--vt-studio-control-stroke: 1px;")
    expect(css).not.toContain("stroke-width: 2.25;")
    expect(css).toContain("border-width: 1.5px;")
    expect(controls).not.toContain("4.09px")
    expect(controls).not.toContain("micro 1px")
    expect(catalog).not.toContain("4.09px")
    expect(catalog).not.toContain("Micro is 12px / 1px")
  })

  it("classifies compact export names into the correct confirmed-library sections", () => {
    const catalog = readFileSync("src/components/studio-hub/StudioHubConfirmedPrimitiveCatalog.tsx", "utf8")
    expect(catalog).toContain("/Text ?Input|Text ?Area|Text ?Box|StudioInput")
    expect(catalog).toContain("/Top ?Split ?Module|Collapsing|Inter ?Module|Split ?Accordion|Upload ?Frame/")
    expect(catalog).toContain("/Publishing ?Card|Brain ?Status ?LED ?Badges|BrainStatusBadge|ResponseMetaRow/")
    expect(catalog.indexOf("if (/Publishing ?Card")).toBeLessThan(catalog.indexOf("if (/Button ?·"))
  })

  it("keeps confirmed-library representatives in a full-width module, not a sidebar column", () => {
    const catalog = readFileSync("src/components/studio-hub/StudioHubConfirmedPrimitiveCatalog.tsx", "utf8")
    const catalogCss = readFileSync("src/styles/studio-confirmed-catalog-modules.css", "utf8")
    expect(catalog).toContain('<div className="vt-confirmed-direct-representatives">')
    expect(catalogCss).toContain(".vt-confirmed-direct-representatives {")
    expect(catalogCss).toContain("grid-column: 1 / -1;")
    expect(catalogCss).toContain(".vt-confirmed-direct-representatives .vt-confirmed-primitive-body > .vt-confirmed-variants")
    expect(catalogCss).toContain("grid-template-columns: minmax(0, 1fr);")
  })

  it("keeps split rails square and labels centered independently of the leading rail", () => {
    const splitCss = readFileSync("src/styles/studio-control-split.css", "utf8")
    const controlCss = readFileSync("src/styles/studio-control-system.css", "utf8")
    expect(splitCss).toContain("aspect-ratio: 1 / 1;")
    expect(splitCss).toContain("--vt-studio-split-rail-size: calc(var(--vt-studio-control-height, 44px) - 2 * var(--vt-studio-control-stroke, 3px));")
    expect(controlCss).toContain("The icon rail and its divider occupy their own column and never bias the label.")
    expect(controlCss).toContain("justify-content: center;")
  })

  it("preserves the primary inline glyph stroke while focused text fill becomes black", () => {
    const css = readFileSync("src/styles/studio-control-system.css", "utf8")
    const fieldsCss = readFileSync("src/styles/studio-control-fields.css", "utf8")
    const controls = readFileSync("src/studio-ui/primitives/StudioControls.tsx", "utf8")
    expect(css).toContain("-webkit-text-stroke: var(--vt-studio-control-text-stroke) var(--vt-field-primary);")
    expect(css).not.toContain('-webkit-text-stroke: var(--vt-studio-control-text-stroke) #000;')
    const focusedFieldContract = fieldsCss.slice(fieldsCss.indexOf("/* Regression recovery: focus changes glyph fill"), fieldsCss.indexOf("/* Read-only TextBox uses"))
    expect(focusedFieldContract).toContain("-webkit-text-stroke-color: var(--vt-field-primary")
    expect(focusedFieldContract).not.toContain("-webkit-text-stroke-color: #000 !important;")
    expect(controls).toContain('inlineStrokeColor: "primary (--pair-a) at 100% opacity"')
    expect(controls).toContain("focused text fill is black while the inline glyph stroke remains primary")
  })

  it("exports and documents the shared split text input primitive", () => {
    const index = readFileSync("src/studio-ui/index.ts", "utf8")
    const catalog = readFileSync("src/components/studio-hub/StudioHubConfirmedPrimitiveCatalog.tsx", "utf8")
    expect(index).toContain('export { StudioSplitTextInput } from "./primitives/StudioSplitTextInput"')
    expect(catalog).toContain('title="Studio Split Text Input · Left + Right + Double"')
    expect(catalog).toContain('data-vt-library-component="StudioSplitTextInput"')
  })
})
