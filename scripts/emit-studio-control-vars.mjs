import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import ts from "typescript"

const root = process.cwd()
const sourcePath = resolve(root, "src/studio-ui/tokens.ts")
const outputPath = resolve(root, "src/styles/studio-control-vars.generated.css")
const source = readFileSync(sourcePath, "utf8")
const sourceFile = ts.createSourceFile(sourcePath, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)

function unwrap(node) {
  while (node && (ts.isAsExpression(node) || ts.isSatisfiesExpression(node) || ts.isParenthesizedExpression(node))) node = node.expression
  return node
}
function property(object, name) {
  const node = unwrap(object)
  if (!node || !ts.isObjectLiteralExpression(node)) throw new Error(`Expected object literal while reading ${name}`)
  const entry = node.properties.find((item) => ts.isPropertyAssignment(item) && (ts.isIdentifier(item.name) || ts.isStringLiteral(item.name)) && item.name.text === name)
  if (!entry || !ts.isPropertyAssignment(entry)) throw new Error(`Missing Studio token property: ${name}`)
  return unwrap(entry.initializer)
}
function numberValue(node, label) {
  if (node && ts.isNumericLiteral(node)) return Number(node.text)
  throw new Error(`Expected numeric Studio token: ${label}`)
}

const declaration = sourceFile.statements
  .filter(ts.isVariableStatement)
  .flatMap((statement) => statement.declarationList.declarations)
  .find((item) => ts.isIdentifier(item.name) && item.name.text === "STUDIO_CONTROL_SIZE_CONTRACT")
if (!declaration?.initializer) throw new Error("Could not locate STUDIO_CONTROL_SIZE_CONTRACT in src/studio-ui/tokens.ts")

const contract = unwrap(declaration.initializer)
const tiers = [
  ["standard", "44"],
  ["compact", "28"],
  ["micro", "14"],
]
const properties = [
  ["height", "height", "px"],
  ["stroke", "stroke", "px"],
  ["radius", "radius", "px"],
  ["fontSize", "font-size", "px"],
  ["fontWeight", "font-weight", ""],
  ["lineHeight", "line-height", ""],
  ["iconSize", "icon-size", "px"],
  ["iconStroke", "icon-stroke", ""],
  ["buttonShadowX", "button-shadow-x", "px"],
  ["buttonShadowY", "button-shadow-y", "px"],
]
const lines = [
  "/* Generated by scripts/emit-studio-control-vars.mjs from STUDIO_CONTROL_SIZE_CONTRACT. Do not edit by hand. */",
  ":root {",
]
for (const [tier, prefix] of tiers) {
  const tierObject = property(contract, tier)
  for (const [sourceKey, cssKey, unit] of properties) {
    const value = numberValue(property(tierObject, sourceKey), `${tier}.${sourceKey}`)
    lines.push(`  --vt-studio-${prefix}-${cssKey}: ${value}${unit};`)
  }
}
lines.push("}", "")
const generated = lines.join("\n")
if (process.argv.includes("--check")) {
  let current = ""
  try { current = readFileSync(outputPath, "utf8") } catch {}
  if (current !== generated) {
    console.error("Generated Studio CSS variables are stale. Run npm run generate:studio-control-vars.")
    process.exitCode = 1
  } else {
    console.log("Generated Studio CSS variables match STUDIO_CONTROL_SIZE_CONTRACT.")
  }
} else {
  writeFileSync(outputPath, generated)
  console.log(`Generated ${outputPath}`)
}
