import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(fileURLToPath(new URL("..", import.meta.url)))
const contractPath = resolve(root, "src/studio-ui/studio-control-size-tiers.json")
const outputPath = resolve(root, "src/styles/studio-control-vars.generated.css")
const contract = JSON.parse(readFileSync(contractPath, "utf8"))

const tiers = [
  ["standard", "44"],
  ["compact", "28"],
  ["micro", "14"],
]
const px = new Set(["height", "stroke", "radius", "fontSize", "iconSize", "buttonShadowX", "buttonShadowY"])
const cssProperty = {
  height: "height",
  stroke: "stroke",
  radius: "radius",
  fontSize: "font-size",
  fontWeight: "font-weight",
  lineHeight: "line-height",
  iconSize: "icon-size",
  iconStroke: "icon-stroke",
  buttonShadowX: "button-shadow-x",
  buttonShadowY: "button-shadow-y",
}

const lines = [
  "/* Generated by scripts/emit-studio-control-vars.mjs. Edit studio-control-size-tiers.json instead. */",
  ":root {",
]
for (const [tier, prefix] of tiers) {
  const values = contract[tier]
  if (!values) throw new Error(`Missing Studio control tier: ${tier}`)
  for (const [key, suffix] of Object.entries(cssProperty)) {
    if (!(key in values)) throw new Error(`Missing ${tier}.${key} in Studio control size contract`)
    const value = values[key]
    lines.push(`  --vt-studio-${prefix}-${suffix}: ${value}${px.has(key) ? "px" : ""};`)
  }
}
lines.push("}", "")
const generated = lines.join("\n")
const check = process.argv.includes("--check")
if (check) {
  let current = ""
  try { current = readFileSync(outputPath, "utf8") } catch {}
  if (current !== generated) {
    console.error("Studio control CSS variables are stale. Run npm run generate:studio-control-vars.")
    process.exitCode = 1
  } else {
    console.log("Studio control CSS variables match the canonical size tier contract.")
  }
} else {
  writeFileSync(outputPath, generated)
  console.log(`Wrote ${outputPath}`)
}
